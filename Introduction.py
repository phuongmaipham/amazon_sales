def extract_features(row):
    text = row["full_text"]

    features = {}

    # ---------------------------------------
    # 1️⃣ BRAND
    # ---------------------------------------
    features["brand"] = row["product_name"].split()[0].lower()

    # ---------------------------------------
    # 2️⃣ LENGTH FEATURES (m, ft, cm)
    # ---------------------------------------
    features["length_m"]  = extract_num(text, r"(\d+(\.\d+)?)\s*m")
    features["length_cm"] = extract_num(text, r"(\d+)\s*cm")
    features["length_ft"] = extract_num(text, r"(\d+)\s*ft")

    # unify
    if features["length_cm"]: features["length_m"] = features["length_cm"] / 100
    if features["length_ft"]: features["length_m"] = features["length_ft"] * 0.3048

    # ---------------------------------------
    # 3️⃣ WATT / POWER
    # ---------------------------------------
    features["watts"] = extract_num(text, r"(\d+)\s*w")

    # ---------------------------------------
    # 4️⃣ CONNECTOR TYPES
    # ---------------------------------------
    features["typec"]      = int(("type-c" in text) or ("type c" in text) or ("usb-c" in text))
    features["micro_usb"]  = int("micro usb" in text)
    features["lightning"]  = int("lightning" in text)
    features["usb_a"]      = int(("usb a" in text) or ("usb-a" in text))

    # ---------------------------------------
    # 5️⃣ FAST CHARGING FEATURES
    # ---------------------------------------
    fast_keywords = [
        "fast charging", "fast charge", "quick charge",
        "qc 3.0", "qc3.0", "power delivery", "pd", "rapid charge"
    ]
    features["fast_charge"] = int(any(kw in text for kw in fast_keywords))

    # ---------------------------------------
    # 6️⃣ MATERIAL
    # ---------------------------------------
    features["braided"]      = int("braided" in text)
    features["nylon"]        = int("nylon" in text)
    features["metal"]        = int("metal" in text or "aluminum" in text)
    features["tangle_free"]  = int("tangle" in text)

    # ---------------------------------------
    # 7️⃣ COLOR DETECTION
    # ---------------------------------------
    colors = ["black","white","red","blue","green","yellow",
              "silver","gold","grey","pink","purple"]
    for c in colors:
        features[f"color_{c}"] = int(c in text)

    # ---------------------------------------
    # 8️⃣ PACK / QUANTITY
    # ---------------------------------------
    features["pack_count"] = extract_num(text, r"pack of (\d+)")

    # ---------------------------------------
    # 9️⃣ DEVICE COMPATIBILITY
    # ---------------------------------------
    device_keywords = ["iphone","ipad","samsung","oneplus","vivo","oppo","android"]
    for d in device_keywords:
        features[f"supports_{d}"] = int(d in text)

    # ---------------------------------------
    # 🔟 DURABILITY SCORE
    # ---------------------------------------
    durability_words = ["durable","strong","reinforced","heat-resistant","heavy-duty","premium"]
    features["durability_score"] = sum(1 for w in durability_words if w in text)

    # ---------------------------------------
    # 1️⃣1️⃣ PRICE BUCKET
    # ---------------------------------------
    features["price_bucket"] = int(row["price"] // 500) if row["price"] else 0

    # ---------------------------------------
    # 1️⃣2️⃣ CATEGORY
    # ---------------------------------------
    features["category_match"] = row["main_category"]

    # ---------------------------------------
    # 1️⃣3️⃣ TEXT FOR TF-IDF
    # ---------------------------------------
    features["keywords"] = text

    return features

