def get_similarity(df, idx1, idx2):
    num_sim  = numeric_sim_matrix[idx1, idx2]
    text_sim = text_sim_matrix[idx1, idx2]

    # category boost
    cat_sim = 1 if df.loc[idx1,"main_category"] == df.loc[idx2,"main_category"] else 0

    # price bucket similarity
    price_sim = 1 if df.loc[idx1,"price_bucket"] == df.loc[idx2,"price_bucket"] else 0

    # final score
    return (0.50 * num_sim) + (0.35 * text_sim) + (0.10 * cat_sim) + (0.05 * price_sim)

def recommend(df, product_id, top_n=5):
    if product_id not in df["product_id"].values:
        return None
    idx = df.index[df["product_id"] == product_id][0]

    scores = [(i, get_similarity(df, idx, i)) for i in range(len(df)) if i != idx]
    scores = sorted(scores, key=lambda x: x[1], reverse=True)
    top_idx = [i[0] for i in scores[:top_n]]

    return df.loc[top_idx, ["product_id","product_name","main_category","price"]]

